#!/usr/bin/env bash
sp_hyprland_version() {
    local output version
    if sp_have hyprctl && [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]]; then output="$(hyprctl version 2>/dev/null || true)"
    elif sp_have Hyprland; then output="$(Hyprland --version 2>/dev/null || true)"
    elif sp_have hyprctl; then output="$(hyprctl version 2>/dev/null || true)"
    else return 1; fi
    version="$(grep -oE '[0-9]+\.[0-9]+(\.[0-9]+)?' <<< "$output" | head -n1)"
    [[ -n "$version" ]] && printf '%s\n' "$version"
}
sp_validate_lua() {
    local file="$1"
    if sp_have luac; then luac -p "$file" || sp_die "Lua syntax validation failed: $file"; sp_ok "Lua syntax validated: $file"
    elif sp_have lua; then lua -e 'assert(loadfile(arg[1]))' "$file" || sp_die "Lua syntax validation failed: $file"; sp_ok "Lua syntax validated: $file"
    else sp_warn "No Lua parser (luac/lua) is installed; syntax validation skipped for $file."; fi
}
sp_generate_monitors_lua() {
    local target="$1" drm_root="${SEKAIPOP_DRM_DIR:-/sys/class/drm}" entry output status mode modes current best_hz
    local -a outputs=()
    for entry in "$drm_root"/card*-*; do
        [[ -f "$entry/status" ]] || continue
        status="$(cat "$entry/status" 2>/dev/null || true)"; [[ "$status" == connected ]] || continue
        output="${entry##*/}"; output="${output#card*-}"
        [[ "$output" =~ ^[A-Za-z0-9_.:-]+$ ]] || continue; outputs+=("$output")
    done
    {
        printf '%s\n' '-- Generated by the SekaiPop installer for currently connected displays.'
        printf '%s\n' '-- Follows SekaiPop upstream: hl.monitor({...}); edit this file or use Settings > Hyprland > Displays.'
        if (("${#outputs[@]}" == 0)); then
            printf '%s\n' '-- No connected DRM output was detected; Hyprland will use its preferred/default output configuration.'
        else
            while IFS= read -r output; do
                [[ -n "$output" ]] || continue
                modes=''; for entry in "$drm_root"/card*-"$output"/modes; do [[ -f "$entry" ]] && { modes="$entry"; break; }; done
                mode='preferred'; current=''
                if [[ -n "$modes" ]]; then current="$(head -n1 "$modes" 2>/dev/null | grep -oE '^[0-9]+x[0-9]+' || true)"; [[ -n "$current" ]] && mode="$current"; fi
                best_hz=''
                if sp_have hyprctl && [[ -n "$current" ]]; then
                    best_hz="$(hyprctl monitors all 2>/dev/null | awk -v output="$output" -v res="$current" '
                        /^Monitor / { current_output=$2 }
                        /availableModes:/ && current_output==output {
                            for (i=2;i<=NF;i++) { split($i,a,"@"); if (a[1]==res) { hz=a[2]; sub(/Hz$/, "", hz); if ((hz+0)>(best+0)) { best=hz+0; best_raw=hz } } }
                        }
                        END { if (best_raw!="") printf "%s", best_raw }')"
                fi
                [[ -n "$best_hz" ]] && mode="${current}@${best_hz}"
                printf '\nhl.monitor({\n    output = "%s",\n    mode = "%s",\n    position = "auto",\n    scale = 1,\n    vrr = 0\n})\n' "$output" "$mode"
            done < <(printf '%s\n' "${outputs[@]}" | sort -u)
        fi
    } > "$target"
}
sp_hyprland_lua_qs_alias_targets_sekaipop() {
    local hypr_dir="$1" variables="$1/hyprland/variables.lua" custom_variables="$1/custom/variables.lua"

    if [[ -f "$custom_variables" ]] && grep -Fq 'load("custom.variables"' "$hypr_dir/hyprland.lua" && awk '
        /^[[:space:]]*--/ { next }
        /^[[:space:]]*QS[[:space:]]*=/ { found=1 }
        END { exit !found }
    ' "$custom_variables"; then
        variables="$custom_variables"
    fi
    [[ -f "$variables" ]] || return 1

    awk '
        /^[[:space:]]*--/ { next }
        /qsConfig[[:space:]]*=[[:space:]]*"sekaipop"/ { config=1 }
        /QS[[:space:]]*=[[:space:]]*"qs -c sekaipop"/ { direct=1 }
        /QS[[:space:]]*=[[:space:]]*"qs -c "[[:space:]]*\.\.[[:space:]]*qsConfig/ { alias=1 }
        END { exit !(direct || (config && alias)) }
    ' "$variables"
}

# Resolve one literal Hyprland source path exactly as the legacy parser does.
# Relative paths are anchored to the file containing source=. No shell eval.
sp_hyprland_conf_resolve_source() {
    local current_file="$1" source_path="$2" current_dir
    [[ -n "$source_path" && "$source_path" != *'$'* ]] || return 1
    if [[ "$source_path" == "~" ]]; then
        printf '%s\n' "$HOME"
    elif [[ "$source_path" == "~/"* ]]; then
        printf '%s/%s\n' "$HOME" "${source_path#~/}"
    elif [[ "$source_path" == /* ]]; then
        printf '%s\n' "$source_path"
    else
        current_dir="${current_file%/*}"
        [[ "$current_dir" != "$current_file" ]] || current_dir='.'
        printf '%s/%s\n' "$current_dir" "$source_path"
    fi
}

# Follow source= directives recursively, respecting relative paths and globbing.
# Cycles are deduplicated; unresolved expressions/missing matches mark the graph ambiguous.
sp_hyprland_conf_collect_files() {
    local root="$1" current canonical source_path pattern candidate index=0
    local -a queue=() matches=()
    local -A seen=()
    SP_HYPRLAND_CONF_FILES=()
    SP_HYPRLAND_AUTOSTART_UNCERTAIN=0
    queue=("$root")
    while (( index < ${#queue[@]} )); do
        if (( ${#SP_HYPRLAND_CONF_FILES[@]} >= 512 )); then
            SP_HYPRLAND_AUTOSTART_UNCERTAIN=1
            sp_warn 'Hyprland source graph exceeded the 512-file inspection limit; autostart detection is incomplete.'
            break
        fi
        current="${queue[index]}"
        index=$((index + 1))
        [[ -f "$current" && -r "$current" ]] || { SP_HYPRLAND_AUTOSTART_UNCERTAIN=1; continue; }
        canonical="$(realpath -m -- "$current" 2>/dev/null || printf '%s' "$current")"
        [[ -z "${seen[$canonical]:-}" ]] || continue
        seen[$canonical]=1
        SP_HYPRLAND_CONF_FILES+=("$current")
        while IFS= read -r source_path; do
            pattern="$(sp_hyprland_conf_resolve_source "$current" "$source_path")" || {
                SP_HYPRLAND_AUTOSTART_UNCERTAIN=1
                continue
            }
            matches=()
            mapfile -t matches < <(compgen -G "$pattern" || true)
            if (("${#matches[@]}" == 0)); then
                SP_HYPRLAND_AUTOSTART_UNCERTAIN=1
                continue
            fi
            for candidate in "${matches[@]}"; do
                if [[ -f "$candidate" ]]; then
                    queue+=("$candidate")
                elif [[ ! -d "$candidate" ]]; then
                    SP_HYPRLAND_AUTOSTART_UNCERTAIN=1
                fi
            done
        done < <(awk '
            /^[[:space:]]*#/ { next }
            /^[[:space:]]*source[[:space:]]*=/ {
                value = $0
                sub(/^[[:space:]]*source[[:space:]]*=[[:space:]]*/, "", value)
                sub(/[[:space:]]+#.*$/, "", value)
                sub(/^[[:space:]]+/, "", value)
                sub(/[[:space:]]+$/, "", value)
                if ((substr(value, 1, 1) == "\"" && substr(value, length(value), 1) == "\"") ||
                    (substr(value, 1, 1) == "\047" && substr(value, length(value), 1) == "\047")) {
                    value = substr(value, 2, length(value) - 2)
                }
                print value
            }
        ' "$current")
    done
}

sp_hyprland_has_quickshell_autostart() {
    local mode="$1" hypr_dir="$2" root file
    local -a files=()
    case "$mode" in
        lua)
            root="$hypr_dir/hyprland.lua"
            files+=("$root")
            if [[ -f "$root" ]] && grep -Fq 'load("hyprland.execs")' "$root"; then
                files+=("$hypr_dir/hyprland/execs.lua")
            fi
            if [[ -f "$root" ]] && grep -Fq 'load("custom.execs"' "$root"; then
                files+=("$hypr_dir/custom/execs.lua")
            fi
            ;;
        conf)
            root="$hypr_dir/hyprland.conf"
            sp_hyprland_conf_collect_files "$root"
            files=("${SP_HYPRLAND_CONF_FILES[@]}")
            ;;
        *) return 1 ;;
    esac
    for file in "${files[@]}"; do
        [[ -f "$file" ]] || continue
        if [[ "$mode" == lua ]]; then
            awk '
                /^[[:space:]]*--/ { next }
                /(qs|quickshell)[[:space:]]+-c[[:space:]]+sekaipop|qs[[:space:]]+-p[[:space:]].*sekaipop/ { found=1 }
                END { exit !found }
            ' "$file" && return 0
            if [[ "$file" == "$hypr_dir/hyprland/execs.lua" || "$file" == "$hypr_dir/custom/execs.lua" ]] &&
                grep -Fq 'load("hyprland.variables")' "$root" &&
                grep -Eq 'hl\.exec_cmd\([[:space:]]*QS[[:space:]]*\)' "$file" &&
                sp_hyprland_lua_qs_alias_targets_sekaipop "$hypr_dir"; then
                return 0
            fi
        else
            awk '
                /^[[:space:]]*#/ { next }
                /^[[:space:]]*exec-once[[:space:]]*=/ && /(qs|quickshell)[[:space:]]+-c[[:space:]]+sekaipop|qs[[:space:]]+-p[[:space:]].*sekaipop/ { found=1 }
                END { exit !found }
            ' "$file" && return 0
        fi
    done
    if [[ "$mode" == conf && "${SP_HYPRLAND_AUTOSTART_UNCERTAIN:-0}" == 1 ]]; then
        return 0
    fi
    return 1
}
sp_write_session_file() {
    local mode="$1" hypr_dir="$2" file tmp cfg req start=1 proposed
    if sp_hyprland_has_quickshell_autostart "$mode" "$hypr_dir"; then
        start=0
        if [[ "$mode" == conf && "${SP_HYPRLAND_AUTOSTART_UNCERTAIN:-0}" == 1 ]]; then
            sp_warn 'The active Hyprland source graph contains unresolved includes. The installer is withholding an additional Quickshell autostart to avoid a duplicate launch; inspect the loaded files and ensure exactly one qs -c sekaipop startup command is configured.'
        fi
    fi
    if [[ "$mode" == lua ]]; then
        file="$hypr_dir/sekaipop_session.lua"; req='pcall(require, "sekaipop_session")'; tmp="$(mktemp "$hypr_dir/.sekaipop-session.XXXXXX")"
        { printf '%s\n' '-- sekaipop_session.lua: generated by SekaiPop; safe to edit or remove.'; printf '%s\n' 'hl.env("ELECTRON_OZONE_PLATFORM_HINT", "auto")'; printf '%s\n' 'hl.on("hyprland.start", function()'; printf '%s\n' '    hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")'; (( start )) && printf '%s\n' '    hl.exec_cmd("qs -c sekaipop")'; printf '%s\n' 'end)'; } > "$tmp"
    else
        file="$hypr_dir/sekaipop_session.conf"; req="source = $hypr_dir/sekaipop_session.conf"; tmp="$(mktemp "$hypr_dir/.sekaipop-session.XXXXXX")"
        { printf '%s\n' '# sekaipop_session.conf: generated by SekaiPop; safe to edit or remove.'; printf '%s\n' 'env = ELECTRON_OZONE_PLATFORM_HINT,auto'; printf '%s\n' 'exec-once = dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP'; (( start )) && printf '%s\n' 'exec-once = qs -c sekaipop'; } > "$tmp"
    fi
    if [[ -e "$file" ]] && cmp -s "$tmp" "$file"; then rm -f -- "$tmp"
    elif [[ -e "$file" ]]; then proposed="$(mktemp "$file.proposed.XXXXXX")"; cat "$tmp" > "$proposed"; rm -f -- "$tmp"; sp_warn "Existing $file was preserved because it differs from the generated version; proposed integration saved to $proposed for review."; return 2
    else mv -f -- "$tmp" "$file"; fi
    cfg="$hypr_dir/hyprland.$mode"; [[ -f "$cfg" ]] || sp_die "Expected Hyprland config does not exist: $cfg"
    sp_atomic_append_once "$cfg" "$req"; [[ "$mode" != lua ]] || sp_validate_lua "$file"
    sp_info "SekaiPop session integration is loaded by $cfg."
}
sp_integrate_hyprland() {
    local source_dir="$1" version stage old mode file
    [[ "$SP_HYPR" == skip ]] && { sp_info 'Hyprland integration skipped (--hypr skip).'; return 0; }
    version="$(sp_hyprland_version || true)"
    if [[ -n "$version" ]] && ! sp_version_ge "$version" 0.55.0; then sp_die "Hyprland $version is below SekaiPop's mandatory 0.55.0 Lua/API baseline. No config was modified. Upgrade Hyprland through your chosen trusted source and rerun."; fi
    if [[ "$SP_HYPR" == full ]]; then
        [[ -d "$source_dir" && -f "$source_dir/hyprland.lua" ]] || sp_die "Full Hyprland source missing: $source_dir/hyprland.lua."
        [[ -n "$version" ]] && sp_version_ge "$version" 0.55.0 || sp_die 'Full mode requires a detectable Hyprland version >= 0.55.0.'
        [[ ! -L "$SP_HYPR_DEST" ]] || sp_die "Refusing to replace symlinked Hyprland config: $SP_HYPR_DEST"
        mkdir -p "$(dirname "$SP_HYPR_DEST")"; stage="$(mktemp -d "$(dirname "$SP_HYPR_DEST")/.hypr-sekaipop-stage.XXXXXX")"
        if ! cp -a "$source_dir/." "$stage/"; then rm -rf -- "$stage"; sp_die 'Could not stage SekaiPop Hyprland configuration.'; fi
        for file in monitors.lua workspaces.lua sekaipop_overrides.lua pjsekai_overrides.lua; do [[ -f "$SP_HYPR_DEST/$file" ]] && { rm -f -- "$stage/$file"; cp -a -- "$SP_HYPR_DEST/$file" "$stage/$file"; }; done
        if [[ -d "$SP_HYPR_DEST/custom" ]]; then rm -rf -- "$stage/custom"; mkdir -p "$stage/custom"; cp -a "$SP_HYPR_DEST/custom/." "$stage/custom/"; fi
        [[ -f "$stage/monitors.lua" ]] || sp_generate_monitors_lua "$stage/monitors.lua"
        [[ ! -f "$stage/sekaipop_overrides.lua" ]] || sp_validate_lua "$stage/sekaipop_overrides.lua"
        sp_validate_lua "$stage/monitors.lua"; sp_validate_lua "$stage/hyprland.lua"
        old="${SP_HYPR_DEST}.sekaipop-old-$SP_TIMESTAMP"
        if [[ -e "$SP_HYPR_DEST" ]]; then mv -- "$SP_HYPR_DEST" "$old" || { rm -rf -- "$stage"; sp_die 'Could not move existing Hyprland config to its protected staging name.'; }; fi
        if mv -- "$stage" "$SP_HYPR_DEST"; then [[ ! -e "$old" ]] || rm -rf -- "$old"; sp_ok "Installed full SekaiPop Hyprland configuration at $SP_HYPR_DEST. Existing config is retained in the installer snapshot."
        else [[ -e "$old" && ! -e "$SP_HYPR_DEST" ]] && mv -- "$old" "$SP_HYPR_DEST"; rm -rf -- "$stage"; sp_die 'Could not activate full Hyprland configuration; the previous config was restored.'; fi
    else
        [[ ! -L "$SP_HYPR_DEST" ]] || sp_die "Refusing to modify symlinked Hyprland config: $SP_HYPR_DEST"
        if [[ -f "$SP_HYPR_DEST/hyprland.lua" ]]; then mode=lua; elif [[ -f "$SP_HYPR_DEST/hyprland.conf" ]]; then mode=conf
        else sp_warn "No hyprland.lua or hyprland.conf found in $SP_HYPR_DEST; merge mode made no changes. Start/configure Hyprland first, or use --hypr skip."; return 0; fi
        sp_write_session_file "$mode" "$SP_HYPR_DEST" || { local rc=$?; (( rc == 2 )) && sp_warn 'Hyprland merge proposal was not auto-activated because a user-owned session file already exists.'; (( rc == 2 )) || return "$rc"; }
    fi
}
